bool buttonPressed()
{
    return digitalRead(BUTTON_PIN) == LOW;
}

void waitForButtonRelease()
{
    while (buttonPressed())
    {
        delay(10);
    }

    delay(50);
}

// ============================================================
// BOOT SCREEN
// ============================================================

void drawBootScreen()
{
    menuTft.fillScreen(TFT_WHITE);

    menuTft.setTextColor(TFT_BLACK, TFT_WHITE);
    menuTft.setTextSize(1);

    // --------------------------------------------------------
    // Title
    // --------------------------------------------------------

    menuTft.setCursor(42, 5);
    menuTft.print("GHOSTWAVE");

    menuTft.drawLine(10, 18, 150, 18, TFT_BLACK);

    // --------------------------------------------------------
    // Logo
    // --------------------------------------------------------

    menuTft.setRotation(1);

    menuTft.drawBitmap(
        40,     // X: centered
        23,     // Y: below title
        ghostwavelogo,
        80,     // width
        90,     // height
        TFT_BLACK,
        TFT_WHITE
    );

    // --------------------------------------------------------
    // Loading bar
    // --------------------------------------------------------

    const int barX = 25;
    const int barY = 116;
    const int barWidth = 110;
    const int barHeight = 7;

    menuTft.drawRect(
        barX,
        barY,
        barWidth,
        barHeight,
        TFT_BLACK
    );

    // Slower loading animation
    for (int progress = 0; progress <= 100; progress += 5)
    {
        int fillWidth = ((barWidth - 2) * progress) / 100;

        menuTft.fillRect(
            barX + 1,
            barY + 1,
            fillWidth,
            barHeight - 2,
            TFT_BLACK
        );

        delay(75);
    }
}

// ============================================================
// MENU
// ============================================================

void drawMenu(int selected)
{
    menuTft.fillScreen(TFT_WHITE);

    menuTft.setTextColor(TFT_BLACK, TFT_WHITE);
    menuTft.setTextSize(1);

    menuTft.setCursor(42, 8);
    menuTft.print("GHOSTWAVE");

    menuTft.drawLine(10, 20, 118, 20, TFT_BLACK);

    // RF Scanner
    menuTft.setCursor(20, 38);

    if (selected == MENU_RF_SCANNER)
    {
        menuTft.print("> RF SCANNER");
    }
    else
    {
        menuTft.print("  RF SCANNER");
    }

    // BLE Mode
    menuTft.setCursor(20, 58);

    if (selected == MENU_BLE_MODE)
    {
        menuTft.print("> BLE MODE");
    }
    else
    {
        menuTft.print("  BLE MODE");
    }

    menuTft.setCursor(20, 90);
    menuTft.print("PRESS = NEXT");

    menuTft.setCursor(20, 103);
    menuTft.print("HOLD  = SELECT");
}

// ============================================================
// SETUP
// ============================================================

void menuSetup()
{
    pinMode(BUTTON_PIN, INPUT_PULLUP);

    menuTft.init();
    menuTft.setRotation(1);

    // Boot animation
    drawBootScreen();

    // Then show the menu
    menuTft.fillScreen(TFT_WHITE);
}

// ============================================================
// MENU SELECTION
// ============================================================

int menuSelect()
{
    int selected = MENU_RF_SCANNER;

    drawMenu(selected);

    while (true)
    {
        if (buttonPressed())
        {
            unsigned long pressStart = millis();

            while (buttonPressed())
            {
                delay(10);
            }

            unsigned long pressDuration = millis() - pressStart;

            // Long press = select
            if (pressDuration >= 600)
            {
                delay(100);
                return selected;
            }

            // Short press = next item
            selected++;

            if (selected >= MENU_COUNT)
            {
                selected = 0;
            }

            drawMenu(selected);

            delay(100);
        }
    }
}
